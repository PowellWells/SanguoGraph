function visualFactionForVolume(volume: number): VisualFaction {
  if (volume <= 5 || (volume >= 9 && volume <= 29)) {
    return 'wei';
  }
  if (volume >= 32 && volume <= 45) {
    return 'shu';
  }
  if (volume >= 46) {
    return 'wu';
  }
  return 'other';
}

const volumeIndexes = new Map<number, number>();

export const sixthRosterManifest: readonly SixthRosterManifestEntry[] =
  rosterSeeds.map(([volume, name, gender = 'male']) => {
    const volumeIndex = (volumeIndexes.get(volume) ?? 0) + 1;
    volumeIndexes.set(volume, volumeIndex);
    const paddedVolume = String(volume).padStart(2, '0');
    const paddedIndex = String(volumeIndex).padStart(2, '0');
    return {
      id: `person:sg:sgz_v${paddedVolume}_${paddedIndex}`,
      name,
      aliases: [],
      volume,
      sectionAnchor: name,
      historicalLayer: 'official_history',
      visualFaction: visualFactionForVolume(volume),
      historicalAffiliations: [],
      disambiguation: `《三国志》卷${volume}列传或附传所载${name}`,
      gender,
    };
  });

