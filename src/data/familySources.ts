function officialSource(
  id: string,
  work: string,
  section: string,
  quotation: string | null,
  reference: string,
  url: string,
): HistoricalSource {
  return {
    id,
    work,
    section,
    author: work === '三国志' ? '陈寿' : '房玄龄等',
    commentator: work === '三国志' ? '裴松之' : null,
    quotation,
    reference,
    url,
    sourceType: 'primary',
    historicalLayer: 'official_history',
    reviewStatus: 'verified',
    note: '第三批家庭扩展的关系级史料条目；仅支持本条明确记载的家庭身份。',
  };
}

