interface RelationSeed {
  slug: string;
  sourcePersonId: string;
  targetPersonId: string;
  type: RelationType;
  sourceId: string;
  qualifier: string;
  historicalLayer?: HistoricalLayer;
  evidenceBasis?: EvidenceBasis;
}

function relation(seed: RelationSeed): Relation {
  const historicalLayer = seed.historicalLayer ?? 'official_history';
  const isAnnotated = historicalLayer === 'annotated_history';
  const claim: RelationClaim = {
    periodLabel: '亲属身份关系；具体起止年未详',
    relationshipQualifier: seed.qualifier,
    evidenceBasis: seed.evidenceBasis ?? 'direct_record',
    modernInterpretation: `按所引史料“${seed.qualifier}”建立对应亲属边。`,
    disputeStatus: isAnnotated ? 'not_assessed' : 'none_recorded',
    decisionStatus: isAnnotated ? 'pending_review' : 'confirmed',
    opposingSourceIds: [],
    scholarlyViews: [],
  };
  return {
    id: `relation:sg:seventh_audit_batch_2_${seed.slug}`,
    sourcePersonId: seed.sourcePersonId,
    targetPersonId: seed.targetPersonId,
    type: seed.type,
    certainty: isAnnotated ? 'probable' : 'confirmed',
    historicalLayer,
    reviewStatus: isAnnotated ? 'pending_review' : 'verified',
    origin: 'recorded',
    sourceIds: [seed.sourceId],
    note: seed.qualifier,
    claim,
  };
}

