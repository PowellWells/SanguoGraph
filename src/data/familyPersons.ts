import type {
  Gender,
  HistoricalLayer,
  Historicity,
  Person,
  ReviewStatus,
  VisualFaction,
} from '../domain';

interface FamilyPersonSeed {
  slug: string;
  name: string;
  sourceId: string;
  visualFaction: VisualFaction;
  factions: readonly string[];
  description: string;
  courtesyName?: string | null;
  gender?: Gender;
  otherNames?: readonly string[];
  historicity?: Historicity;
  reviewStatus?: ReviewStatus;
  sourceLayer?: HistoricalLayer;
}

function person(seed: FamilyPersonSeed): Person {
  const sourceLayer = seed.sourceLayer ?? 'official_history';
  return {
    id: `person:sg:${seed.slug}`,
    name: seed.name,
    courtesyName: seed.courtesyName ?? null,
    otherNames: [...(seed.otherNames ?? [])],
    gender: seed.gender ?? 'male',
    birthYear: null,
    deathYear: null,
    clan: null,
    factions: [...seed.factions],
    visualFaction: seed.visualFaction,
    importBatch: 3,
    description: seed.description,
    historicity: seed.historicity ?? 'historical',
    reviewStatus: seed.reviewStatus ?? 'verified',
    sourceIds: [seed.sourceId],
    externalIds: {},
    note:
      sourceLayer === 'official_history'
        ? '第三批家庭扩展人物；身份按所引史籍核验，未核验的生卒年保持空值。'
        : '第三批家庭扩展人物；属于后出记载或文学层，不与正史人物身份混同。',
  };
}

